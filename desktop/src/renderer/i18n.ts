export type TranslationKey=keyof typeof en;

export function translate(language:LanguagePreference,key:TranslationKey,values:Record<string,string|number>={}):string{
  const template=(language==="zh-CN"?zh:en)[key];
  return Object.entries(values).reduce((value,[name,replacement])=>value.replaceAll(`{${name}}`,String(replacement)),template);
}

export function localeLanguage(locale:string):LanguagePreference{
  return locale.trim().toLowerCase().startsWith("zh")?"zh-CN":"en";
}
